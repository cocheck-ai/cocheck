// Generates the "Supported agents" table in README.md from the harness manifests, so the README cannot drift from them.
// `node scripts/readme-agents.ts` exits 1 when the README's table differs from the manifests; `--write` rewrites the table.
// Built-in manifests: harnesses/<key>/. Kit manifests (not built in): public-kit/harness/harnesses/<key>/.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const START = "<!-- supported-agents:start (generated by scripts/readme-agents.ts; do not edit by hand) -->";
export const END = "<!-- supported-agents:end -->";

interface Row {
  name: string;
  versions: string;
  where: string;
}

function manifests(dir: string, where: string): Row[] {
  if (!existsSync(dir)) return [];
  const rows: Row[] = [];
  for (const key of readdirSync(dir).sort()) {
    const file = path.join(dir, key, "cocheck-harness.json");
    if (!existsSync(file)) continue;
    const m = JSON.parse(readFileSync(file, "utf8")) as { displayName: string; fullName?: string; testedVersions?: string[] };
    const versions = m.testedVersions ?? [];
    rows.push({ name: m.fullName ?? m.displayName, versions: versions.length === 0 ? "not listed" : versions.join(", "), where });
  }
  return rows;
}

/** The generated block, markers included. */
export function renderAgents(root: string): string {
  const rows = [
    ...manifests(path.join(root, "harnesses"), "built in"),
    ...manifests(path.join(root, "public-kit", "harness", "harnesses"), "harness kit (loaded from your data folder)"),
  ];
  const lines = ["| Agent | Tested versions | How it is supported |", "| --- | --- | --- |", ...rows.map((r) => `| ${r.name} | ${r.versions} | ${r.where} |`)];
  return `${START}\n${lines.join("\n")}\n${END}`;
}

/** The README text with its generated block replaced; throws when the markers are missing. */
export function withBlock(readme: string, block: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md has no supported-agents markers");
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

/** True when the README's block matches the manifests. */
export function readmeIsCurrent(root: string): boolean {
  const readme = readFileSync(path.join(root, "README.md"), "utf8");
  return withBlock(readme, renderAgents(root)) === readme;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.join(import.meta.dirname, "..");
  const file = path.join(root, "README.md");
  const readme = readFileSync(file, "utf8");
  const next = withBlock(readme, renderAgents(root));
  if (process.argv.includes("--write")) {
    if (next !== readme) writeFileSync(file, next);
    console.log(next === readme ? "README.md supported agents: already current" : "README.md supported agents: written");
  } else if (next !== readme) {
    console.error("README.md supported agents are out of date; run: node scripts/readme-agents.ts --write");
    process.exit(1);
  } else console.log("README.md supported agents: current");
}
